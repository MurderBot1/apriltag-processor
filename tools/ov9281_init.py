"""OV9281 (OV9282 family) register init for 1280x800 RAW8, 2-lane MIPI @ 400 MHz DDR (800 Mb/s/lane), 120 fps.
Register values are taken from the mainline Linux driver drivers/media/i2c/ov9282.c (common_regs,
bitdepth_regs RAW8, mode_1280x800_regs). Timing: HTS = 1600 px (800 byte-clk @100 MHz), VTS = 1041 lines
-> 200 Mpix/s / (1600*1041) = 120.1 fps.   Output: rtl/sensor_init.hex, one 24-bit word per write {addr16, data8};
address 0xFFFF = delay of `data` * 1 ms.
"""
import os

COMMON = [(0x0302, 0x32), (0x030e, 0x02), (0x3001, 0x00), (0x3004, 0x00), (0x3005, 0x00), (0x3006, 0x04),
          (0x3011, 0x0a), (0x3013, 0x18), (0x301c, 0xf0), (0x3022, 0x01), (0x3030, 0x10), (0x3039, 0x32),
          (0x303a, 0x00), (0x3503, 0x08), (0x3505, 0x8c), (0x3507, 0x03), (0x3508, 0x00), (0x3610, 0x80),
          (0x3611, 0xa0), (0x3620, 0x6e), (0x3632, 0x56), (0x3633, 0x78), (0x3666, 0x00), (0x366f, 0x5a),
          (0x3680, 0x84), (0x3712, 0x80), (0x372d, 0x22), (0x3731, 0x80), (0x3732, 0x30), (0x377d, 0x22),
          (0x3788, 0x02), (0x3789, 0xa4), (0x378a, 0x00), (0x378b, 0x4a), (0x3799, 0x20), (0x3881, 0x42),
          (0x38a8, 0x02), (0x38a9, 0x80), (0x38b1, 0x00), (0x38c4, 0x00), (0x38c5, 0xc0), (0x38c6, 0x04),
          (0x38c7, 0x80), (0x3920, 0xff), (0x4010, 0x40), (0x4043, 0x40), (0x4307, 0x30), (0x4317, 0x00),
          (0x4501, 0x00), (0x450a, 0x08), (0x4601, 0x04), (0x470f, 0x00), (0x4f07, 0x00), (0x5000, 0x9f),
          (0x5001, 0x00), (0x5e00, 0x00), (0x5d00, 0x07), (0x5d01, 0x00), (0x0101, 0x01), (0x1000, 0x03),
          (0x5a08, 0x84)]
RAW8 = [(0x030d, 0x60), (0x3662, 0x07)]
MODE_1280x800 = [(0x3778, 0x00), (0x3800, 0x00), (0x3801, 0x00), (0x3802, 0x00), (0x3803, 0x00), (0x3804, 0x05),
                 (0x3805, 0x0f), (0x3806, 0x03), (0x3807, 0x2f), (0x3808, 0x05), (0x3809, 0x00), (0x380a, 0x03),
                 (0x380b, 0x20), (0x3810, 0x00), (0x3811, 0x08), (0x3812, 0x00), (0x3813, 0x08), (0x3814, 0x11),
                 (0x3815, 0x11), (0x3820, 0x40), (0x3821, 0x00), (0x4003, 0x40), (0x4008, 0x04), (0x4009, 0x0b),
                 (0x400c, 0x00), (0x400d, 0x07), (0x4507, 0x00), (0x4509, 0x00)]
HTS_REG = 800         # register counts 2 pixels: (1280 + hblank 320) / 2
VTS = 1041
EXPOSURE = 128        # lines  (~1 ms)
GAIN = 0x30


def sequence():
    s = [(0x0103, 0x01), (0xFFFF, 5)]                                   # software reset, 5 ms
    s += COMMON + RAW8 + MODE_1280x800
    s += [(0x380c, HTS_REG >> 8), (0x380d, HTS_REG & 255), (0x380e, VTS >> 8), (0x380f, VTS & 255)]
    e = EXPOSURE << 4
    s += [(0x3308, 0x01), (0x3500, e >> 16 & 255), (0x3501, e >> 8 & 255), (0x3502, e & 255), (0x3509, GAIN), (0x3308, 0x00)]
    s += [(0x0100, 0x01)]                                               # stream on
    return s


if __name__ == '__main__':
    seq = sequence()
    with open(os.path.join(os.path.dirname(__file__), '..', 'rtl', 'sensor_init.hex'), 'w') as f:
        for a, d in seq: f.write(f'{(a << 8) | d:06x}\n')
    print(len(seq), 'register writes')
    fps = 200e6 / (1600 * VTS)
    print(f'frame rate {fps:.2f} fps; line = {1600/200:.2f} us = 800 byte clocks @100 MHz')
