"""Generate tag36h11 images + firmware code table; self-check against reference apriltag lib."""
import os, sys, numpy as np, cv2
sys.path.insert(0, os.path.dirname(__file__))
from geom import ROOT
CELL = 64
D = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_APRILTAG_36h11)

def tag_bits(tid):
    """8x8 bool array, True = white, border black."""
    img = cv2.aruco.generateImageMarker(D, tid, 8, borderBits=1) if hasattr(cv2.aruco, 'generateImageMarker') else None
    return (img > 127)

def tag_image(tid, margin=1):
    b = tag_bits(tid)
    n = 8 + 2 * margin
    im = np.full((n, n), 255, np.uint8)
    im[margin:margin + 8, margin:margin + 8] = np.where(b, 255, 0)
    return cv2.resize(im, (n * CELL, n * CELL), interpolation=cv2.INTER_NEAREST)

def code_of(tid):
    b = tag_bits(tid)[1:7, 1:7]          # 6x6 data, row-major from top-left, as seen
    v = 0
    for r in range(6):
        for c in range(6):
            v = (v << 1) | int(b[r, c])
    return v

if __name__ == '__main__':
    out = os.path.join(ROOT, 'test_images', 'tags'); os.makedirs(out, exist_ok=True)
    codes = [code_of(i) for i in range(587)]
    for i in (3, 17, 42, 58, 77, 101, 133, 202, 250, 311, 404, 515):
        cv2.imwrite(os.path.join(out, f'tag36h11_{i:03d}.png'), tag_image(i))
    # border must be all black in every tag
    for i in range(587):
        b = tag_bits(i); assert not b[0].any() and not b[7].any() and not b[:, 0].any() and not b[:, 7].any()
    assert len(set(codes)) == 587
    with open(os.path.join(ROOT, 'firmware', 'core', 'tag36h11_codes.h'), 'w') as f:
        f.write('/* generated by tools/make_tags.py : 6x6 data bits, row-major from top-left as seen,\n'
                '   MSB = first cell, bit set = white cell. */\n#pragma once\n#include <stdint.h>\n'
                '#define TAG36H11_COUNT 587\nstatic const uint64_t tag36h11_codes[587] = {\n')
        for i in range(0, 587, 4):
            f.write('  ' + ' '.join(f'0x{c:09x}ULL,' for c in codes[i:i + 4]) + '\n')
        f.write('};\n')
    # cross-check with the real AprilTag library
    from pupil_apriltags import Detector
    det = Detector(families='tag36h11')
    bad = 0
    for i in range(0, 587):
        im = tag_image(i)[::4, ::4]
        r = det.detect(np.ascontiguousarray(im))
        if len(r) != 1 or r[0].tag_id != i: bad += 1
    print('mismatch vs apriltag lib:', bad, 'of 587')
    assert bad == 0
